const assert = require('node:assert/strict');
const { chromium } = require(process.env.SLIDES_PLAYWRIGHT_MODULE || 'playwright');
const draft = '```yaml\nid: opening\ncues: arrived, accepted\n```\n\n# Café 🦊\n\n:::motion {cue=accepted after=missing}\nWorker starts.\n:::\n\n[Jump](#opening/accepted)\n\n```text\naccepted\n```\n\n<!-- notes -->\n\n---\n\n```yaml\nid: recovery\ncues: accepted\n```\n\n# Recovery\n\n:::motion {cue=accepted}\nOther scope.\n:::\n';
(async () => {
  const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader'], ...(process.env.SLIDES_BROWSER ? { executablePath: process.env.SLIDES_BROWSER } : {}) });
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 800 } }), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(process.argv[2] + '#1', { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => window.SlidesNav);
    const saved = await page.evaluate(async () => (await (await fetch('/_slides/source')).json()).source);
    await page.keyboard.press('e');
    await page.locator('[data-status]').filter({ hasText: 'Ready to edit' }).waitFor();
    const input = page.locator('#slides-source');
    await input.fill(draft);
    await page.locator('[data-outline]').getByRole('button', { name: '1 · Café 🦊', exact: true }).waitFor();
    await page.locator('[data-diagnostics]').getByRole('button', { name: /unknown cue "missing"/ }).waitFor();
    let published = 0;
    page.on('request', request => { if (request.url().endsWith('/presenter/state')) published++; });
    const slide = await page.evaluate(() => SlidesNav.current());
    await page.locator('[data-diagnostics]').getByRole('button', { name: /unknown cue "missing"/ }).click();
    assert.equal(await input.evaluate(el => el.value.slice(el.selectionStart, el.selectionEnd)), 'missing', 'ranged Unicode selection');
    assert.equal(await page.evaluate(() => SlidesNav.current()), slide, 'diagnostic selection does not navigate');
    await page.locator('[data-symbol-search]').fill('accepted');
    await page.locator('[data-symbols]').getByRole('button', { name: 'cue · accepted', exact: true }).first().click();
    assert.equal(await input.evaluate(el => el.value.slice(el.selectionStart, el.selectionEnd)), 'accepted');
    assert.equal(await page.locator('[data-references] button').count(), 3);
    await page.locator('[data-symbol-name]').fill('arrived');
    await page.getByRole('button', { name: 'Rename in draft', exact: true }).click();
    await page.locator('[data-status]').filter({ hasText: 'already exists' }).waitFor();
    assert.equal(await input.inputValue(), draft, 'collision preserves draft');
    await page.locator('[data-symbol-name]').fill('processed');
    await page.getByRole('button', { name: 'Rename in draft', exact: true }).click();
    await page.locator('[data-status]').filter({ hasText: 'Renamed in draft' }).waitFor();
    const renamed = await input.inputValue();
    assert.ok(renamed.includes('#opening/processed') && renamed.includes('cue=processed after=missing'));
    assert.ok(renamed.includes('```text\naccepted') && renamed.includes('id: recovery\ncues: accepted'), 'rename keeps other scopes/code');
    await page.getByRole('button', { name: 'Undo source', exact: true }).click();
    assert.equal(await input.inputValue(), draft);
    await page.keyboard.press('Control+Shift+z');
    assert.equal(await input.inputValue(), renamed, 'keyboard redo');
    await page.getByRole('button', { name: 'Close source editor', exact: true }).click();
    await page.keyboard.press('e');
    assert.equal(await input.inputValue(), renamed, 'closing keeps unsaved work');
    await page.getByRole('button', { name: 'Preview slide 2', exact: true }).click();
    assert.equal(await page.evaluate(() => SlidesNav.current()), 2);
    await page.waitForTimeout(200);
    assert.equal(published, 0, 'source selections and authoring preview never publish audience state');
    await page.keyboard.press('e');
    await page.getByRole('button', { name: 'Reload source', exact: true }).click();
    await page.locator('[data-status]').filter({ hasText: 'Ready to edit' }).waitFor();
    assert.equal(await input.inputValue(), saved);
    assert.equal(await page.evaluate(async () => (await (await fetch('/_slides/source')).json()).source), saved, 'tools leave disk untouched');
    await page.setViewportSize({ width: 390, height: 844 });
    const bounds = await page.locator('.slides-source-panel').boundingBox();
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390 && bounds.y >= 0 && bounds.y + bounds.height <= 844, 'mobile editor fits');
    const saveBounds = await page.getByRole('button', { name: 'Save and preview', exact: true }).boundingBox();
    assert.ok(saveBounds.y >= bounds.y && saveBounds.y + saveBounds.height < 844, 'mobile save controls stay visible');
    await page.locator('[data-symbol-search]').scrollIntoViewIfNeeded();
    await input.focus();
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.slides-source-panel').isVisible(), false, 'native Escape/focus behavior');
    assert.deepEqual(errors, []);
    console.log('Source tools browser passed: diagnostics, Unicode ranges, scoped rename/collision, undo/redo, draft retention, silent preview, mobile.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
